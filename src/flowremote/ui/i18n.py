def translate_text(value: str, lang: str = "zh") -> str:
    if lang != "zh" or not value:
        return value
    leading = value[: len(value) - len(value.lstrip())]
    trailing = value[len(value.rstrip()) :]
    core = " ".join(value.split())
    if not core:
        return value
    exact = ZH_PHRASES.get(core)
    if exact:
        return leading + exact + trailing
    translated = core
    for pattern, replacement in ZH_PATTERNS:
        translated = pattern.sub(replacement, translated)
    translated = _ZH_RE.sub(lambda m: ZH_PHRASES[m.group(1)], translated)
    return leading + translated + trailing


def translate_html(document: str, lang: str = "zh") -> str:
    if lang != "zh":
        return document
    protected: list[str] = []

    def stash(match: re.Match[str]) -> str:
        protected.append(match.group(0))
        return _I18N_TOKEN % (len(protected) - 1)

    document = _PROTECTED.sub(stash, document)
    document = re.sub(
        r">([^<>]+)<",
        lambda match: ">" + translate_text(match.group(1), lang) + "<",
        document,
    )
    document = re.sub(
        r'\b(placeholder|aria-label|title|alt)="([^"]*)"',
        lambda match: (
            f'{match.group(1)}="{html.escape(translate_text(match.group(2), lang), quote=True)}"'
        ),
        document,
    )
    for index, value in enumerate(protected):
        document = document.replace(_I18N_TOKEN % index, value)
    return document


